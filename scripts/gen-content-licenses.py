#!/usr/bin/env python3
"""Regenerate Content/LICENSES.md from Content/licenses.json.

Usage: python3 scripts/gen-content-licenses.py
Only files present in the public tree (not *.nc.json) are listed as distributed.
"""
import json
from collections import OrderedDict
from pathlib import Path

root = Path(__file__).resolve().parent.parent
entries = json.loads((root / "Content" / "licenses.json").read_text())


def esc(s):
    return s.replace("|", "\\|").replace("\n", " ")


def short(lic):
    return lic.split(" (", 1)[0] if len(lic) > 60 else lic


dist = [e for e in entries if not e["file"].endswith(".nc.json")]
held = [e for e in entries if e["file"].endswith(".nc.json")]

groups = OrderedDict()
for e in dist:
    groups.setdefault((e["source"], e["license"]), []).append(e)

out = ["# Content licences", "",
       "<!-- Generated by scripts/gen-content-licenses.py from Content/licenses.json. Do not edit by hand. -->", "",
       "Tenaz-original content (and all code) is MIT, see `/LICENSE`. Everything below is third-party or derived "
       "material that keeps its own licence. Per-file provenance is in `Content/licenses.json`; the format is "
       "described in `Content/FORMAT.md`. Every Content file that is not listed below is original to Tenaz and "
       "covered by the MIT licence.", "",
       "## Share-alike (CC BY-SA): attribution and same-licence terms apply", ""]
sa = [(k, v) for k, v in groups.items() if v[0]["tier"] == "share-alike"]
out += ["The files below are derived from CC BY-SA sources. Copies and adaptations of these files must keep "
        "the attribution and be shared under the same (or a compatible) licence; the rest of the repository "
        "is not affected.", "",
        "| Source | Licence | Files | Attribution |", "|---|---|---|---|"]
def row(k, v):
    files = "<br>".join(f"`Content/{e['file']}`" for e in v)
    url = v[0]["url"].split(" ; ")[0]
    name = f"[{esc(k[0])}]({url})" if url.startswith("http") else esc(k[0])
    return f"| {name} | {esc(short(k[1]))} | {files} | {esc(v[0]['attribution'])} |"
out += [row(k, v) for k, v in sa]
out += ["", "## Permissive and original sources", "",
        "| Source | Licence | Files | Attribution |", "|---|---|---|---|"]
out += [row(k, v) for k, v in groups.items() if v[0]["tier"] != "share-alike"]
notes = [(k, v) for k, v in groups.items() if len(k[1]) > 60]
# Upstream rights the dataset licence may not fully cover (stated so nobody relies on more than the tag).
UPSTREAM = {
    "OneStopEnglish corpus and OneStopQA": "the texts come from onestopenglish.com (Macmillan) articles based on Guardian news; the corpus "
               "authors release them under CC BY-SA 4.0, but the rights in the underlying articles were not "
               "independently verified.",
    "args.me (webis/args_me)": "the arguments were crawled from debate portals (idebate.org, debatewise.org and others) whose own "
               "terms were not independently verified.",
}
for label, text in UPSTREAM.items():
    used = [v for k, v in groups.items() if label.split(" (")[0].split(" and ")[0] in k[0]]
    if used:
        notes.append(((label, text), used[0]))
if notes:
    out += ["", "### Licence caveats", ""]
    for k, v in notes:
        out.append(f"- **{k[0]}**: {k[1]}")
out += ["", "## Not distributed", "",
        "These sources are non-commercial, research-only or have no clear licence. Their files use the "
        "`*.nc.json` suffix, are gitignored, and only exist in the owner's local builds. They are not part of "
        "this repository or its releases.", ""]
seen = OrderedDict()
for e in held:
    seen.setdefault(e["source"], e["tier"])
out += [f"- {s} ({t})" for s, t in seen.items()]
out.append("")
(root / "Content" / "LICENSES.md").write_text("\n".join(out))
